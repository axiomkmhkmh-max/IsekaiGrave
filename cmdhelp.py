def _home(uid: int) -> tuple:
    lines = ["همه‌ی دستورها ساده‌ان؛ فقط بنویسشون یا از منوی / بزن.",
             "«(ریپلای)» یعنی باید روی پیامِ یه بازیکن ریپلای کنی.", "┈┈┈┈┈┈┈┈┈┈"]
    lines += [f"{ic} <b>{title}</b> — {sub}" for ic, title, sub, _ in CATS.values()]
    lines += ["┈┈┈┈┈┈┈┈┈┈", "🎯 گیج شدی؟ «زندگی من» رو بنویس و دکمه‌ها رو بزن."]
    keys = list(CATS)
    btns = [btn(f"{CATS[k][0]} {CATS[k][1]}", f"hc:{k}:{uid}", "blue") for k in keys]
    rows = [btns[i:i + 2] for i in range(0, len(btns), 2)]
    return panel("purple", "📚", "همه‌ی دستورهای بازی", lines), kb(*rows)


def _cat(key: str, uid: int) -> tuple:
    ic, title, _sub, cmds = CATS[key]
    lines = [f"• <b>{c}</b> ← {d}" for c, d in cmds]
    return panel("purple", ic, title, lines), kb([btn("📚 همه‌ی دسته‌ها", f"hc:main:{uid}", "blue"), btn("🌙 منو", f"m:main:{uid}", "green")])


async def do_commands(m):
    text, markup = _home(m.from_user.id)
    await m.reply(text, reply_markup=markup)


async def cmds_cb(cq, parts: list):
    """hc:main:<uid> · hc:<cat>:<uid>"""
    await cq.answer()
    key = parts[1] if len(parts) > 1 else "main"
    uid = cq.from_user.id
    text, markup = _home(uid) if key == "main" or key not in CATS else _cat(key, uid)
    await safe_edit(cq.message, text, markup)
